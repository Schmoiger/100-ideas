def test_generate_workflows(tmp_path: Path):
    templates_dir = tmp_path / "context" / "templates"
    templates_dir.mkdir(parents=True)

    template_file = templates_dir / "pr-sample-template.yml"
    template_content = (
        "name: Sample\non: [push]\njobs:\n  sample:\n    runs-on: ubuntu-latest\n"
    )
    template_file.write_text(template_content)

    results = generate_workflows(tmp_path)

    target_file = tmp_path / ".github" / "workflows" / "pr-sample.yml"
    assert target_file.exists()
    assert (
        "Auto-generated by context/scripts/generators/generate_adapters.py — do not edit manually"
        in target_file.read_text()
    )
    assert template_content in target_file.read_text()
    assert target_file in results
